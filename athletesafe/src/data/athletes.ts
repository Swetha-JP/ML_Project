const generateRiskTrend = (currentScore: number, days: number) => {
  const trend: { date: string; score: number }[] = [];
  const now = new Date('2026-09-06');
  for (let i = days; i >= 0; i--) {
    const date = new Date(now);
    date.setDate(date.getDate() - i);
    const variance = (Math.random() - 0.5) * 14;
    const dayScore = Math.max(10, Math.min(95, currentScore + variance - (i * 0.15)));
    trend.push({
      date: date.toISOString().split('T')[0],
      score: Math.round(dayScore),
    });
  }
  trend[trend.length - 1].score = currentScore;
  return trend;
};

